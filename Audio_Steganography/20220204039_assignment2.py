def decode_audio(encoded_file):

    # Open the encoded WAV file
    with wave.open(encoded_file, 'rb') as wav_in:
        n_channels = wav_in.getnchannels()
        sample_width = wav_in.getsampwidth()
        n_frames = wav_in.getnframes()
        frames = wav_in.readframes(n_frames)

    # Convert frames to list of integers (samples)
    if sample_width == 1:  # 8-bit audio (unsigned)
        samples = list(struct.unpack(f'{n_frames * n_channels}B', frames))
    elif sample_width == 2:  # 16-bit audio (signed)
        samples = list(struct.unpack(f'{n_frames * n_channels}h', frames))
    else:
        raise ValueError(f"Unsupported sample width: {sample_width}")

    # Extract the LSB from each sample and reconstruct the binary message
    bits = []
    for sample in samples:
        bits.append(str(sample & 1))

    # Convert bits back to characters (8 bits per character)
    binary_string = ''.join(bits)
    chars = []
    for i in range(0, len(binary_string), 8):
        byte = binary_string[i:i+8]
        if len(byte) < 8:
            break
        char = chr(int(byte, 2))
        chars.append(char)
        # Stop if we find the delimiter
        if ''.join(chars).endswith("####"):
            break

    decoded_message = ''.join(chars)

    # Remove the delimiter
    if "####" in decoded_message:
        decoded_message = decoded_message.split("####")[0]

    return decoded_message

