def encode_audio(input_file, output_file, secret_message):
    # Open the WAV file
    with wave.open(input_file, 'rb') as wav_in:
        # Get audio parameters
        n_channels = wav_in.getnchannels()
        sample_width = wav_in.getsampwidth()
        framerate = wav_in.getframerate()
        n_frames = wav_in.getnframes()

        # Read all frames
        frames = wav_in.readframes(n_frames)

    # Convert frames to list of integers (samples)
    # Using struct to unpack the binary data
    if sample_width == 1:  # 8-bit audio (unsigned)
        samples = list(struct.unpack(f'{n_frames * n_channels}B', frames))
    elif sample_width == 2:  # 16-bit audio (signed)
        samples = list(struct.unpack(f'{n_frames * n_channels}h', frames))
    else:
        raise ValueError(f"Unsupported sample width: {sample_width}")

# Prepare the secret message (Convert secret message + delimiter to binary)

    # Add delimiter to mark end of message
    secret_message_with_delimiter = secret_message + "####"

    # Convert message to binary string
    binary_message = ''.join(format(ord(char), '08b') for char in secret_message_with_delimiter)

    # Check if audio has enough capacity for the message
    if len(binary_message) > len(samples):
        raise ValueError(f"Message too long! Need {len(binary_message)} bits but only {len(samples)} available.")

    # Embed the message bit by bit into the LSB of each sample
    encoded_samples = samples.copy()

    for i, bit in enumerate(binary_message):
        # Clear the LSB and set it to the message bit
        encoded_samples[i] = (encoded_samples[i] & ~1) | int(bit)

    # Convert back to binary data
    if sample_width == 1:
        encoded_data = struct.pack(f'{len(encoded_samples)}B', *encoded_samples)
    elif sample_width == 2:
        encoded_data = struct.pack(f'{len(encoded_samples)}h', *encoded_samples)
    else:
        raise ValueError(f"Unsupported sample width: {sample_width}")

    # Write the encoded audio to a new WAV file
    with wave.open(output_file, 'wb') as wav_out:
        wav_out.setnchannels(n_channels)
        wav_out.setsampwidth(sample_width)
        wav_out.setframerate(framerate)
        wav_out.writeframes(encoded_data)

    print(f"\n Message encoded and saved to {output_file}")
    print(f"   - Message: '{secret_message}'")
    print(f"   - Message length: {len(secret_message)} characters")
    print(f"   - Bits embedded: {len(binary_message)} bits")
    print(f"   - Audio capacity: {len(samples)} bits")
    print(f"   - Used: {(len(binary_message) / len(samples) * 100):.2f}% of capacity")

